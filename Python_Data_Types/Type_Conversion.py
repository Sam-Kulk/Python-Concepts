# Type Conversion
x = 914
y = 863.95

# int to float(Basically it will add '.0' to the number)
u = float(x)
print(u)
print(type(u))

# float to int(Basically it will just remove the . & decimal numbers)
v = int(y)
print(v)
print(type(v))

# int & float to str
w = 1
x = 1.2
print(str(w),str(x))

