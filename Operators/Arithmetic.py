# These operators are used to perform mathematical operations on two values or variables

a = 10
b = 3

# 1. Addition
add = a+b
print(add)

# 2. Subtraction
sub = a-b
print(sub)

# 3. Multiplication
mul = a*b
print(mul)

# Note: I can use '*' to multiply strings
print("a"*2)

# 4. Division
div = a/b   # gives division answer
print(div)

# 5. % Modulus
modulus = a%b   # gives reminder answer
print(modulus)

